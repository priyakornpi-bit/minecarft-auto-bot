package com.example.client.state;

/**
 * กำหนดสถานะการทำงานหลักของบอท (Finite State Machine - FSM)
 * เพื่อให้ระบบทำงานอย่างเป็นลำดับขั้นตอนและหลีกเลี่ยงพฤติกรรมที่ขัดแย้งกัน
 */
public enum BotState {
    /** อยู่ในสถานะพัก ตรวจสอบความปลอดภัย หรือรอรับคำสั่งใหม่ */
    IDLE,

    /** นำทางและรวบรวมทรัพยากรเป้าหมาย (ตัดไม้ / ขุดแร่ / วิ่งไปเก็บไอเทมตกพื้น) */
    GATHERING,

    /** โหมดคราฟต์ไอเทม: สั่งเปิดโต๊ะคราฟต์ และจัดวางวัตถุดิบลง Crafting Grid 3x3 */
    CRAFTING,

    /** จัดระเบียบกระเป๋า: ตรวจสอบและดรอปไอเทมขยะที่ไม่จำเป็นออกจากตัว */
    CLEANUP_INVENTORY,

    /** โหมดกู้คืนระบบ: ปิดหน้าต่าง GUI ทั้งหมด ปล่อยปุ่มควบคุม และรีเซ็ตสถานะเมื่อติดขัด */
    RECOVERY
}

